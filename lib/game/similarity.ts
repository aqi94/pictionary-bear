export function normalizeWord(s: string): string {
  return s
    .toLowerCase()
    .normalize("NFD")
    .replace(/[̀-ͯ]/g, "")
    .replace(/[^a-z0-9 ]+/g, " ")
    .replace(/\s+/g, " ")
    .trim();
}

export function levenshtein(a: string, b: string): number {
  if (a === b) return 0;
  if (!a.length) return b.length;
  if (!b.length) return a.length;
  let prev = new Array<number>(b.length + 1);
  let cur = new Array<number>(b.length + 1);
  for (let j = 0; j <= b.length; j++) prev[j] = j;
  for (let i = 1; i <= a.length; i++) {
    cur[0] = i;
    for (let j = 1; j <= b.length; j++) {
      const cost = a[i - 1] === b[j - 1] ? 0 : 1;
      cur[j] = Math.min(prev[j] + 1, cur[j - 1] + 1, prev[j - 1] + cost);
    }
    [prev, cur] = [cur, prev];
  }
  return prev[b.length];
}

export type GuessResult = "correct" | "close" | "wrong";

export function judgeGuess(guess: string, word: string): GuessResult {
  const g = normalizeWord(guess);
  const w = normalizeWord(word);
  if (!g) return "wrong";
  if (g === w) return "correct";
  // "close" only for reasonably long words so that 3-letter words don't leak
  if (w.length >= 4 && levenshtein(g, w) <= 1) return "close";
  return "wrong";
}
